package com.restaurant.model;

/** Groups menu items so they can be displayed and searched by section. */
public enum MenuCategory {
    /** Small dishes served before the main course. */
    APPETIZER,
    /** Primary meal dishes. */
    MAIN_COURSE,
    /** Sweet dishes served after a meal. */
    DESSERT,
    /** Drinks offered by the restaurant. */
    BEVERAGE,
    /** Extra dishes ordered alongside a main course. */
    SIDE
}
